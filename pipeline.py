"""## 1. Download
Up to n_sectors of TESS 2-minute SPOC light curves. Always returns a list (one per sector).
"""

def _network_errors():
    """Exception types that mean 'the network/MAST failed', worth retrying."""
    errs = [TimeoutError, ConnectionError]
    try:
        import requests
        errs.append(requests.exceptions.RequestException)
    except ImportError:
        pass
    try:
        from astroquery.exceptions import RemoteServiceError
        errs.append(RemoteServiceError)
    except ImportError:
        pass
    return tuple(errs)

def download(star_name, n_sectors=1, attempts=3, waits=(30, 90)):
    """Download up to n_sectors of TESS 2-min SPOC light curves. Returns a list.
    Network failures (timeouts, dropped connections, MAST errors, empty downloads) are
    retried up to `attempts` times, waiting `waits` seconds in between. "No 2-minute data"
    is an answer, not a failure, and is never retried. (2026-11-24; data unchanged.)
    """
    for attempt in range(attempts):
        try:
            search = lk.search_lightcurve(star_name, mission="TESS",
                                          author="SPOC", exptime=120)
            if len(search) == 0:
                raise ValueError(f"No TESS 2-minute data found for {star_name}")
            lcs = search[:n_sectors].download_all()
            if lcs is None or len(lcs) == 0:
                raise ConnectionError(f"Download returned nothing for {star_name}")
            return list(lcs)
        except _network_errors():
            if attempt == attempts - 1:
                raise
            time.sleep(waits[min(attempt, len(waits) - 1)])

# Header keyword → TIC catalog column (same quantity, same units: K, cgs dex, solar radii)
TIC_COLUMNS = {"TEFF": "Teff", "LOGG": "logg", "RADIUS": "rad"}

def _missing(x):
    """True if a header/catalog value is absent: None, empty, masked or NaN."""
    try:
        return x is None or np.ma.is_masked(x) or not np.isfinite(float(x))
    except (TypeError, ValueError):
        return True

def get_star_info(lc):
    """Stellar Teff, log g and radius. Uses the light-curve header first; only values that
    are missing (None or NaN) are filled from the TIC catalog (MAST).
    Returns (star_info, source), e.g. source = {"TEFF": "header", "LOGG": "TIC", ...}.
    """
    info = {k: lc.meta.get(k) for k in TIC_COLUMNS}
    source = {}
    for k in info:
        if _missing(info[k]):
            info[k], source[k] = None, "missing"
        else:
            info[k], source[k] = float(info[k]), "header"

    if None in info.values():
        tic = lc.meta.get("TICID")
        try:
            from astroquery.mast import Catalogs
            row = Catalogs.query_criteria(catalog="Tic", ID=int(tic))[0]
            for k, col in TIC_COLUMNS.items():
                if info[k] is None and not _missing(row[col]):
                    info[k], source[k] = float(row[col]), "TIC"
        except Exception as e:                       # no TIC ID / network trouble → stay N/A
            print(f"TIC lookup failed for TIC {tic}: {type(e).__name__}")
    return info, source

"""---
# 2. Cleaning
clean(): one sector. Remove NaNs → trim 0.25 d before/after data gaps (spacecraft ramps)
→ remove high outliers (never low: transits are low) → flatten with a ~24 h window,
masking transits when their timing is known.
clean_all(): clean each sector separately, then join (each sector has its own
brightness level and drifts; smoothing across gaps would invent fake trends).
"""

def plain(x):
    """Turn an astropy/lightkurve value (units or hidden masks) into a plain float."""
    return float(np.asarray(getattr(x, "value", x)))

def clean(lc, window_length=721, period=None, t0=None, duration=None, trim=0.25):
    """Clean ONE sector. If period/t0/duration are given, transits are masked while flattening."""
    lc = lc.remove_nans()
    lc = lk.LightCurve(time=lc.time,
                       flux=np.asarray(lc.flux.value),
                       flux_err=np.asarray(lc.flux_err.value))

    # Trim spacecraft ramps after and before each data gap
    t = np.asarray(lc.time.value, dtype=float)
    restarts = np.r_[t[0], t[1:][np.diff(t) > 0.5]]
    stops = np.r_[t[:-1][np.diff(t) > 0.5], t[-1]]
    keep = np.ones(len(t), dtype=bool)
    for start in restarts:
        keep &= ~((t >= start) & (t < start + trim))
    for stop in stops:
        keep &= ~((t <= stop) & (t > stop - trim))
    lc = lc[keep]

    lc = lc.remove_outliers(sigma_upper=4, sigma_lower=float("inf"))

    mask = None
    if period is not None:                           # mask transits (1.5× duration wide)
        P, T0, D = plain(period), plain(t0), plain(duration)
        t = np.asarray(lc.time.value, dtype=float)
        phase = (t - T0 + 0.5 * P) % P - 0.5 * P
        mask = np.abs(phase) < 0.75 * D
    return lc.flatten(window_length=window_length, mask=mask)

def clean_all(lcs, period=None, t0=None, duration=None):
    """Clean each sector separately, then join into one light curve."""
    cleaned = []
    for lc in lcs:
        c = clean(lc, period=period, t0=t0, duration=duration)
        c["sector"] = np.full(len(c), int(lc.meta.get("SECTOR") or len(cleaned)))  # for odd/even
        cleaned.append(c)
    return lk.LightCurveCollection(cleaned).stitch()

"""---
# 3. Period search
Box Least Squares on ONE sector (fast; across years the period grid would need to be
far finer). Longest period searched = half the data span, so every signal repeats ≥ 2×.
"""

def search(lc, min_period=0.5, max_period=10, n_periods=10000, plot=False):
    """BLS search. Returns period, t0, duration, depth of the strongest signal."""
    t = np.asarray(lc.time.value, dtype=float)
    max_period = min(max_period, (t.max() - t.min()) / 2)

    periods = np.linspace(min_period, max_period, n_periods)
    pg = lc.to_periodogram(method="bls", period=periods,
                           duration=[0.05, 0.08, 0.1, 0.15, 0.2])
    if plot:
        pg.plot()
    return (pg.period_at_max_power, pg.transit_time_at_max_power,
            pg.duration_at_max_power, pg.depth_at_max_power)

def search_near(lc, period_hint, tol=0.02, n_periods=2000):
    """BLS search restricted to ±tol around a known period (e.g. a TOI's).
    v2 rule (2026-11-24, approved): ALWAYS use the 1× window when it fits in the data (half
    the span); ½× and 2× are only used if 1× doesn't fit. Simulations: safe (planets at the
    correct period and EBs at 2× catalog still caught) but neutral; real dev data: rescues
    LTT 1445 A b and TOI-2266, which the old "highest power wins" rule put at 2× / ½×.
    Returns period, t0, duration, depth, and which multiple was used ("1×", "½×", "2×").
    """
    t = np.asarray(lc.time.value, dtype=float)
    half_span = (t.max() - t.min()) / 2
    best, windows = None, {}
    for factor, label in [(1, "1×"), (0.5, "½×"), (2, "2×")]:
        P = factor * plain(period_hint)
        if P * (1 + tol) > half_span:                  # must repeat ≥ 2× in the sector
            continue
        periods = np.linspace(P * (1 - tol), P * (1 + tol), n_periods)
        pg = lc.to_periodogram(method="bls", period=periods,
                               duration=[0.05, 0.08, 0.1, 0.15, 0.2])
        power = plain(pg.max_power)
        windows[label] = (power, pg)
        if best is None or power > best[0]:
            best = (power, label, pg)
    if best is None:
        raise ValueError(f"Period hint {plain(period_hint):.3f} d is longer than half the data span")
    if "1×" in windows:                                     # v2: always 1× when available
        best = (windows["1×"][0], "1×", windows["1×"][1])
    _, label, pg = best
    return (pg.period_at_max_power, pg.transit_time_at_max_power,
            pg.duration_at_max_power, pg.depth_at_max_power, label)

"""---
# 4. Transit model and fit
Limb-darkened batman model with impact parameter b (well-behaved near edge-on, unlike
inclination). fit_transit flags any parameter at a bound or whose error bar crosses one
(its ± is unreliable → report a limit). Multi-sector fits start from a 1-sector answer so
the period doesn't drift across long time gaps.
"""

def transit_model(t, t0, per, rp, a, b, u1, u2):
    """Limb-darkened transit light curve (batman). Inclination is computed from b."""
    params = batman.TransitParams()
    params.t0, params.per, params.rp, params.a = t0, per, rp, a
    params.inc = np.degrees(np.arccos(np.clip(b / a, 0, 1)))
    params.ecc, params.w = 0.0, 90.0                          # circular orbit
    params.u, params.limb_dark = [u1, u2], "quadratic"
    return batman.TransitModel(params, t).light_curve(params)

def plot_fit(t, f, popt):
    """Folded data + model (top) and residuals (bottom)."""
    xph = (t - popt[0] + 0.5 * popt[1]) % popt[1] - 0.5 * popt[1]
    model = transit_model(t, *popt)
    order = np.argsort(xph)
    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(8, 6), sharex=True,
                                   gridspec_kw={"height_ratios": [3, 1]})
    ax1.plot(xph, f, ".", ms=2, alpha=0.4, label="TESS data")
    ax1.plot(xph[order], model[order], "r-", lw=2, label="model")
    ax1.set_ylabel("Normalized flux"); ax1.legend()
    ax2.plot(xph, f - model, ".", ms=2, alpha=0.4)
    ax2.axhline(0, color="r")
    ax2.set_xlabel("Days from transit center"); ax2.set_ylabel("Data − model")
    plt.show()

LD_TABLE_GLOB = "data/claret2017_tess_quadratic_*.csv"   # dated snapshot(s); newest is used
LD_PRIOR_SIGMA = 0.1
MAXFEV = 20000          # curve_fit function-evaluation limit (default ~100 × n_params; deep EBs hit it)
_ld_interp = None

def ld_prior_for(star_info, sigma=LD_PRIOR_SIGMA):
    """Gaussian limb-darkening prior (u1, u2, σ) from the Claret (2017) TESS quadratic table,
    interpolated linearly in (Teff, log g). Returns (prior, source): prior is None (free
    q1, q2) if there's no table, Teff/log g are missing, or the star is outside the table.
    """
    global _ld_interp
    import glob, os
    from scipy.interpolate import LinearNDInterpolator
    teff, logg = star_info.get("TEFF"), star_info.get("LOGG")
    if teff is None or logg is None:
        return None, "free (no Teff/log g)"
    if _ld_interp is None:
        here = os.path.dirname(os.path.abspath(__file__))
        files = sorted(glob.glob(os.path.join(here, LD_TABLE_GLOB)))
        if not files:
            return None, "free (no LD table)"
        tab = pd.read_csv(files[-1], comment="#")
        _ld_interp = (LinearNDInterpolator(tab[["Teff", "logg"]].values, tab[["u1", "u2"]].values),
                      os.path.basename(files[-1]))
    interp, name = _ld_interp
    u1, u2 = np.ravel(interp(teff, logg))[:2]
    if not (np.isfinite(u1) and np.isfinite(u2)):
        return None, "free (outside LD table)"
    return (float(u1), float(u2), sigma), f"prior {u1:.3f}, {u2:.3f} ± {sigma} ({name})"

def q_to_u(q1, q2):
    """Kipping (2013): q1, q2 in [0, 1] ↔ every physical quadratic limb-darkening law."""
    sq = np.sqrt(q1)
    return 2 * sq * q2, sq * (1 - 2 * q2)

def u_to_q(u1, u2):
    """Inverse of q_to_u (clipped into [0, 1], for starting guesses)."""
    tot = u1 + u2
    q1 = np.clip(tot**2, 0, 1)
    q2 = np.clip(u1 / (2 * tot), 0, 1) if tot > 0 else 0.5
    return q1, q2

def _u_jacobian(q1, q2):
    """d(u1, u2)/d(q1, q2), for carrying error bars from q to u."""
    sq = np.sqrt(max(q1, 1e-12))
    return np.array([[q2 / sq,             2 * sq],
                     [(1 - 2 * q2) / (2 * sq), -2 * sq]])

def _noise(f):
    """Per-point flux scatter from point-to-point differences (ignores slow trends/transits)."""
    return 1.4826 * np.median(np.abs(np.diff(f))) / np.sqrt(2)

def _ld_fit(model_x, t, f, guess, bounds, ld_prior, sigma_f):
    """curve_fit on parameters x = [..., q1, q2] (q1, q2 last). A Gaussian prior on (u1, u2)
    is added as two extra 'data points': the fit pays ((u − u_table)/σ)² for straying.
    """
    n = len(t)
    if ld_prior is None:
        y, sig = f, np.full(n, sigma_f)
        func = lambda _, *x: model_x(t, *x)
    else:
        u1c, u2c, sp = ld_prior
        y = np.r_[f, u1c, u2c]
        sig = np.r_[np.full(n, sigma_f), sp, sp]
        func = lambda _, *x: np.r_[model_x(t, *x), q_to_u(x[-2], x[-1])]
    popt, pcov = curve_fit(func, np.arange(len(y)), y, p0=guess, bounds=bounds, sigma=sig,
                           maxfev=MAXFEV)
    chi2 = np.sum(((y - func(None, *popt)) / sig) ** 2)
    return popt, pcov, chi2

def fit_transit(lc, period, t0, duration, depth, start=None, start_errs=None,
                plot=False, verbose=False, return_pcov=False, ld_prior=None):
    """Fit the transit model. `start` = a previous best fit; `start_errs` = its uncertainties
    (sets how far timing may move). Limb darkening is fitted as Kipping q1, q2 ∈ [0, 1]
    (only physical profiles); ld_prior = (u1, u2, σ) adds a Gaussian prior, None = free.
    Returns: popt, errs, inc, inc_err, flags  (popt/errs in terms of u1, u2)
    (+ the covariance matrix pcov if return_pcov=True)
    """
    P0, T00, D = plain(period), plain(t0), plain(duration)
    if start is not None:                                     # use refined timing
        T00, P0 = start[0], start[1]
    t = np.asarray(lc.time.value, dtype=float)
    f = np.asarray(lc.flux.value, dtype=float)
    ph = (t - T00 + 0.5 * P0) % P0 - 0.5 * P0
    near = np.abs(ph) < max(2 * D, 0.1)                       # only points near transits
    t, f = t[near], f[near]

    if start is None:                                         # guesses from physics
        u_guess = ld_prior[:2] if ld_prior is not None else (0.3, 0.2)
        guess = [T00, P0, np.sqrt(max(plain(depth), 1e-5)),   # depth ≈ (Rp/Rs)²
                 4.2 * P0 ** (2 / 3), 0.3, *u_to_q(*u_guess)] # Kepler, Sun-like star
        dt, dP = 0.02, 0.002
    else:                                                     # refine: window = 5× previous error
        guess = list(start[:5]) + list(u_to_q(start[5], start[6]))
        dt = max(0.01, 5 * start_errs[0]) if start_errs is not None else 0.01
        dP = max(0.0001, 5 * start_errs[1]) if start_errs is not None else 0.0001
    # Rp/Rs may reach 1.0: eclipsing binaries can be star-sized (bug fix, 2026-11-24)
    # Limb darkening as q1, q2 ∈ [0, 1] (Kipping 2013), 2026-11-24
    bounds = ([guess[0] - dt, guess[1] - dP, 0.01, 1.5,   0.0, 0.0, 0.0],
              [guess[0] + dt, guess[1] + dP, 1.00, 100.0, 1.2, 1.0, 1.0])

    # Keep every starting guess inside its bounds (a very deep eclipse used to give a
    # guess Rp/Rs = sqrt(depth) above the cap → curve_fit crashed). Guesses already inside
    # are unchanged.
    guess = np.clip(guess, bounds[0], bounds[1])

    model_x = lambda tt, t0_, per, rp, a, b, q1, q2: transit_model(tt, t0_, per, rp, a, b,
                                                                   *q_to_u(q1, q2))
    x, pcov_x, _ = _ld_fit(model_x, t, f, guess, bounds, ld_prior, _noise(f))

    # Back to u1, u2 (what transit_model and the vetting checks use), errors via Jacobian
    J = np.eye(7)
    J[5:, 5:] = _u_jacobian(x[5], x[6])
    popt = np.r_[x[:5], q_to_u(x[5], x[6])]
    pcov = J @ pcov_x @ J.T
    errs = np.sqrt(np.diag(pcov))

    # Inclination from b and a/Rs, with error propagation (partial derivatives)
    a_fit, b_fit = popt[3], popt[4]
    s = np.sqrt(1 - (b_fit / a_fit) ** 2)
    inc = np.degrees(np.arccos(b_fit / a_fit))
    J = np.array([b_fit / (a_fit**2 * s), -1 / (a_fit * s)])
    inc_err = np.degrees(np.sqrt(J @ pcov[3:5, 3:5] @ J))

    # Flag parameters at a bound, or whose error bar reaches past one
    flags = []
    x_errs = np.sqrt(np.diag(pcov_x))
    for name, val, err, lo, hi in zip(PARAM_NAMES[:5] + ["q1", "q2"], x, x_errs,
                                      bounds[0], bounds[1]):
        width = hi - lo
        if val - lo < max(0.01 * width, err) or hi - val < max(0.01 * width, err):
            flags.append(name)
    if flags and verbose:
        print("⚠️ At a boundary (± unreliable → report a limit):", flags)

    if plot:
        plot_fit(t, f, popt)
    if return_pcov:
        return popt, errs, inc, inc_err, flags, pcov
    return popt, errs, inc, inc_err, flags

def per_sector_ephemeris(lcs, popt1, errs1, duration, depth, ld_prior=None):
    """Timing fix (2026-11-24). A transit TIME is measured far more precisely than a period from
    one sector, so: measure the transit time in each later sector (BLS at the 1-sector period to
    locate it, then a fit), count whole orbits N_k = round((t_k − t_1)/P_1), and fit one weighted
    straight line t_k = T0 + N_k·P. A sector whose time is more than P/4 from a whole orbit is
    left out (orbit count ambiguous) and noted. Returns T0, P, σ_T0, σ_P, notes.
    Simulation (hard case, sims/ephemeris_proto_sim.py): correct period 33% → 70%, median
    |ΔP| 126 s → 0.7 s; EBs at 2× catalog still caught (100%)."""
    t1, P1 = popt1[0], popt1[1]
    pts = [(0.0, t1, max(errs1[0], 1e-5))]
    notes = []
    for lc in lcs[1:]:
        try:
            c = clean(lc)
            pg = c.to_periodogram(method="bls", period=P1 * np.array([1 - 1e-6, 1, 1 + 1e-6]),
                                  duration=[0.05, 0.08, 0.1, 0.15, 0.2])   # BLS needs ≥ 2 periods
            tk0 = plain(pg.transit_time_at_max_power)
            ck = clean(lc, period=P1, t0=tk0, duration=duration)
            pk, ek, *_ = fit_transit(ck, P1, tk0, duration, depth, ld_prior=ld_prior)
        except Exception as e:
            notes.append(f"S{lc.meta.get('SECTOR')}: fit failed ({type(e).__name__})"); continue
        N = np.round((pk[0] - t1) / P1)
        if abs(pk[0] - (t1 + N * P1)) > P1 / 4:
            notes.append(f"S{lc.meta.get('SECTOR')}: orbit count ambiguous"); continue
        pts.append((N, pk[0], max(ek[0], 1e-5)))
    if len(pts) < 2:
        return t1, P1, errs1[0], errs1[1], notes
    N, t, e = map(np.array, zip(*pts))
    A = np.vstack([np.ones_like(N), N]).T / e[:, None]
    coef, *_ = np.linalg.lstsq(A, t / e, rcond=None)
    cov = np.linalg.inv(A.T @ A)
    return coef[0], coef[1], np.sqrt(cov[0, 0]), np.sqrt(cov[1, 1]), notes

"""---
# 5. Upper limits
When b is stuck near 0 (nearly edge-on), its ± is meaningless. profile_b fixes b on a grid,
refits everything else, and finds where χ² worsens by 4 → 95% upper limit on b.
"""

def profile_b(lc, popt, b_max=1.0, n=21, plot=False, ld_prior=None):
    """95% upper limit on b by profile scan. Returns (b_upper, inc_lower),
    or (None, None) if the data can't limit b within the scanned range.
    Limb darkening as in fit_transit (q1, q2; optional prior, included in χ²).
    """
    t = np.asarray(lc.time.value, dtype=float)
    f = np.asarray(lc.flux.value, dtype=float)
    P, T0 = popt[1], popt[0]
    near = np.abs((t - T0 + 0.5 * P) % P - 0.5 * P) < 0.2
    t, f = t[near], f[near]
    sigma = np.std(f - transit_model(t, *popt))              # noise per point

    b_grid = np.linspace(0, b_max, n)
    chi2 = []
    for bb in b_grid:
        def model_fixed_b(t, t0, per, rp, a, q1, q2):        # b locked at bb
            return transit_model(t, t0, per, rp, a, bb, *q_to_u(q1, q2))
        start = [popt[0], popt[1], popt[2], popt[3], *u_to_q(popt[5], popt[6])]
        lo = [popt[0] - 0.01, popt[1] - 0.0001, 0.01, 1.5,   0.0, 0.0]
        hi = [popt[0] + 0.01, popt[1] + 0.0001, 1.00, 100.0, 1.0, 1.0]    # Rp/Rs cap = fit_transit's
        start = np.clip(start, lo, hi)
        _, _, c2 = _ld_fit(model_fixed_b, t, f, start, (lo, hi), ld_prior, sigma)
        chi2.append(c2)

    dchi2 = np.array(chi2) - min(chi2)
    above = np.where(dchi2 >= 4)[0]                          # first grid point past Δχ² = 4
    if len(above) == 0:                                      # never 95% worse → unconstrained
        b_upper, inc_lower = None, None
    else:
        i = above[0]
        b_upper = (np.interp(4, [dchi2[i - 1], dchi2[i]], [b_grid[i - 1], b_grid[i]])
                   if i > 0 else b_grid[0])
        inc_lower = np.degrees(np.arccos(b_upper / popt[3]))

    if plot:
        plt.figure()
        plt.plot(b_grid, dchi2, "o-")
        plt.axhline(4, ls="--", color="red", label="Δχ² = 4 (~95%)")
        plt.xlabel("Impact parameter b (fixed)"); plt.ylabel("Δχ²"); plt.legend()
        plt.show()
    return b_upper, inc_lower

"""---
# 6. Vetting checks
- odd_even: alternating depths → eclipsing binary with unequal stars
- secondary_eclipse: big dip half an orbit later → glowing companion star
  (a tiny dip can be a hot planet's own thermal emission)
- density_check: transit density (Kepler) vs catalog density (log g + radius)
"""

def get_popt(results):
    """Best-fit parameter list from an analyze_star results dictionary."""
    return [results[name][0] for name in PARAM_NAMES]

def _single_depths(t, f, t0, P, T14, core_half, shift=0.0):
    """Depth of each FULLY covered transit window centred at t0 + shift + k·P:
    rows of (parity, depth, white-noise error, n points). Windows cut by a data gap are
    skipped (partial transits near gaps are distorted by ramps/trimming/detrending)."""
    cad = np.median(np.diff(t))
    n = np.round((t - t0 - shift) / P)
    dt = t - (t0 + shift + n * P)
    rows = []
    for k in np.unique(n[np.abs(dt) <= core_half]):
        tc = t0 + shift + k * P
        w = np.abs(t - tc) <= T14 / 2
        tw = t[w]
        full = (w.sum() > 1 and tw.min() <= tc - T14 / 2 + 2 * cad
                and tw.max() >= tc + T14 / 2 - 2 * cad and np.diff(tw).max() < 10 * cad)
        m = (n == k) & (np.abs(dt) <= core_half)
        if full and m.sum() >= 3:
            rows.append((int(k % 2), 1 - f[m].mean(), f[m].std() / np.sqrt(m.sum()), m.sum()))
    return np.array(rows, dtype=float).reshape(-1, 4)

def odd_even(lc, popt, plot=False, n_null=300, seed=0):
    """Compare depths of odd vs even transits. Returns (depth_odd, depth_even, sigma);
    sigma is None if either group has no fully covered transit.
    v3 (2026-11-24): (1) only fully covered transits are used; (2) the error is inflated by
    a red-noise factor β measured from ~300 FAKE transits placed out of transit (the spread
    of fake single-transit depths relative to their white-noise errors; β ≥ 1). The real
    signal cannot leak into β. Simulations (sims/oddeven_sim.py): false FAILs on planets in
    red noise 57% → 0%; EBs with 15% depth difference still caught (100% white, 63% red).
    """
    t = np.asarray(lc.time.value, dtype=float)
    f = np.asarray(lc.flux.value, dtype=float)
    t0, P = popt[0], popt[1]
    grid = np.linspace(-0.5, 0.5, 20001)
    mg = transit_model(t0 + grid * P, *popt)
    T14 = np.mean(mg < 1) * P                                   # transit duration (days)
    core_half = 0.5 * np.mean(mg < 1 - 0.8 * (1 - mg.min())) * P  # deepest part, half-width

    per = _single_depths(t, f, t0, P, T14, core_half)
    if len(per) == 0 or len(np.unique(per[:, 0])) < 2:
        print("Odd/even: not enough fully covered transits in both groups")
        return None, None, None

    # red-noise factor from fake transits away from the transit and from phase 0.5
    rng = np.random.default_rng(seed)
    frac = T14 / P
    allowed = np.r_[np.linspace(2 * frac, 0.5 - 2 * frac, 400),
                    np.linspace(0.5 + 2 * frac, 1 - 2 * frac, 400)]
    z = []
    for sh in rng.choice(allowed, n_null) * P:
        d = _single_depths(t, f, t0, P, T14, core_half, shift=sh)
        if len(d):
            z.extend((d[:, 1] - np.median(d[:, 1])) / d[:, 2])
    beta = max(1.0, float(np.std(z))) if len(z) > 30 else 1.0

    def group(rows):
        dep, err = [], []
        for parity in [0, 1]:                                   # 0 = even, 1 = odd
            g = rows[rows[:, 0] == parity]
            dep.append(np.sum(g[:, 1] * g[:, 3]) / g[:, 3].sum())   # mean of all core points
            err.append(beta * np.sqrt(1 / np.sum(1 / g[:, 2] ** 2)))
        return dep, err

    depths, errs = group(per)                                   # overall (for the printout)

    # Within-sector comparison (2026-11-24, approved): crowding corrections differ between
    # sectors, so transit depths can differ by sector; if odd and even transits come unequally
    # from the sectors, that looks like an odd/even difference. Compare odd vs even INSIDE each
    # sector, then combine (inverse-variance). One sector → identical to v3.
    # Simulation (sims/oddeven_within_sector_sim.py): crowded-field planets falsely failed
    # 10% → 0%; EBs still caught 100%.
    sectors = (np.asarray(lc["sector"]) if "sector" in lc.colnames
               else np.zeros(len(t), dtype=int))
    num = den = 0.0
    for s in np.unique(sectors):
        m = sectors == s
        ps = _single_depths(t[m], f[m], t0, P, T14, core_half)
        if len(ps) == 0 or len(np.unique(ps[:, 0])) < 2:
            continue                                            # needs both parities
        d, e = group(ps)
        e2 = e[0] ** 2 + e[1] ** 2
        num += (d[0] - d[1]) / e2
        den += 1 / e2
    if den == 0:
        print("Odd/even: no sector has fully covered odd AND even transits")
        return depths[1], depths[0], None
    sigma = abs(num / den) * np.sqrt(den)

    if plot:
        n = np.round((t - t0) / P)
        phase = t - (t0 + n * P)
        near = np.abs(phase) < 0.15
        for parity, label in [(0, "even"), (1, "odd")]:
            sel = near & (n % 2 == parity)
            plt.plot(phase[sel], f[sel], ".", ms=2, alpha=0.4, label=label)
        plt.xlabel("Days from transit center"); plt.ylabel("Normalized flux")
        plt.legend(); plt.show()

    n_even, n_odd = int((per[:, 0] == 0).sum()), int((per[:, 0] == 1).sum())
    print(f"Even depth = {depths[0]:.5f} ± {errs[0]:.5f} ({n_even} transits)")
    print(f"Odd depth  = {depths[1]:.5f} ± {errs[1]:.5f} ({n_odd} transits)")
    print(f"Red-noise factor β = {beta:.2f}")
    print(f"Difference = {sigma:.1f}σ → " + ("OK, planet-like" if sigma < 3 else "⚠️ suspicious"))
    return depths[1], depths[0], sigma

def secondary_eclipse(lc, popt, plot=False):
    """Look for a dip half an orbit after transit (circular orbit assumed).
    Returns (depth, error, sigma, ratio to transit depth).
    """
    t = np.asarray(lc.time.value, dtype=float)
    f = np.asarray(lc.flux.value, dtype=float)
    t0, P = popt[0], popt[1]
    phase = ((t - t0) / P) % 1                     # 0 = transit, 0.5 = half an orbit later
    grid = np.linspace(t0 - 0.5 * P, t0 + 0.5 * P, 5000)
    dur = np.mean(transit_model(grid, *popt) < 1)  # transit duration as fraction of orbit

    win = np.abs(phase - 0.5) < 0.4 * dur
    base = (np.abs(phase - 0.5) > dur) & (np.abs(phase - 0.5) < 0.25)
    depth = np.mean(f[base]) - np.mean(f[win])
    err = np.sqrt(np.var(f[win]) / win.sum() + np.var(f[base]) / base.sum())
    sigma = depth / err
    ratio = depth / (1 - transit_model(np.array([t0]), *popt)[0])

    if plot:
        sel = np.abs(phase - 0.5) < 0.2
        bins = np.linspace(0.3, 0.7, 41)
        centers = 0.5 * (bins[1:] + bins[:-1])
        binned = [np.mean(f[sel][(phase[sel] >= lo) & (phase[sel] < hi)])
                  for lo, hi in zip(bins[:-1], bins[1:])]
        plt.plot(phase[sel], f[sel], ".", ms=1, alpha=0.2, color="gray")
        plt.plot(centers, binned, "o-", color="red", label="binned average")
        plt.axvspan(0.5 - 0.5 * dur, 0.5 + 0.5 * dur, alpha=0.15,
                    label="where a secondary eclipse would be")
        plt.ylim(0.998, 1.002)
        plt.xlabel("Orbital phase (0.5 = half an orbit after transit)")
        plt.ylabel("Normalized flux"); plt.legend(); plt.show()

    print(f"Secondary depth = {depth*1e6:.0f} ± {err*1e6:.0f} ppm ({sigma:.1f}σ), "
          f"{ratio*100:.1f}% of transit depth")
    return depth, err, sigma, ratio

def density_check(results):
    """Transit stellar density vs catalog (log g + radius), with uncertainties.
    Returns (rho_cat, ratio, sigma, weak) or None if no catalog data.
    """
    info = results.get("star_info", {})
    logg, R = info.get("LOGG"), info.get("RADIUS")
    if logg is None or R is None:
        print("No catalog log g / radius → can't run the density check")
        return None
    g = 10 ** float(logg)                                            # cm/s²
    rho_cat = 3 * g / (4 * np.pi * 6.674e-8 * float(R) * 6.957e10)   # g/cm³ (CGS)
    rho_cat_err = 0.3 * rho_cat              # catalog log g ±0.1 dex + radius error → ~30%
    rho_fit, rho_fit_err = results["density"]
    ratio = rho_fit / rho_cat
    sigma = abs(rho_fit - rho_cat) / np.sqrt(rho_fit_err**2 + rho_cat_err**2)
    weak = rho_fit_err > 0.5 * rho_fit       # transit density too uncertain to test anything
    print(f"Catalog ρ★ = {rho_cat:.2f} ± {rho_cat_err:.2f}, transit ρ★ = {rho_fit:.2f} ± "
          f"{rho_fit_err:.2f} g/cm³ → ratio {ratio:.2f}, {sigma:.1f}σ" + (" (WEAK)" if weak else ""))
    return rho_cat, ratio, sigma, weak

def grazing_check(results):
    """Is the transit grazing (the object only clips the stellar edge, b + Rp/Rs > 1)?
    Profile-likelihood test (same idea as profile_b): refit with b + Rp/Rs ≤ 1 forced
    (b = s·(1 − Rp/Rs), 0 ≤ s ≤ 1) and see how much worse χ² gets. Returns (g, sigma):
    g = b + Rp/Rs − 1 at the best fit; sigma = √Δχ² (one-sided), 0 if the best fit isn't grazing.
    (Replaces the covariance rule, 2026-11-24: simulations showed it had ~no power.)
    """
    popt = get_popt(results)
    g = popt[4] + popt[2] - 1
    if g <= 0:
        return g, 0.0
    lc, prior = results["lc"], results.get("ld_prior")
    t = np.asarray(lc.time.value, dtype=float)
    f = np.asarray(lc.flux.value, dtype=float)
    P, T0 = popt[1], popt[0]
    near = np.abs((t - T0 + 0.5 * P) % P - 0.5 * P) < 0.2
    t, f = t[near], f[near]
    sig = _noise(f)
    lo = [T0 - 0.01, P - 0.0001, 0.01, 1.5,   0.0, 0.0, 0.0]
    hi = [T0 + 0.01, P + 0.0001, 1.00, 100.0, 1.2, 1.0, 1.0]
    q = u_to_q(popt[5], popt[6])

    def best(model, starts, hi_):
        out = np.inf
        for st in starts:
            try:
                _, _, c2 = _ld_fit(model, t, f, np.clip(st, lo, hi_), (lo, hi_), prior, sig)
                out = min(out, c2)
            except (RuntimeError, ValueError):
                pass
        return out

    free = lambda tt, t0, per, k, a, b, q1, q2: transit_model(tt, t0, per, k, a, b, *q_to_u(q1, q2))
    forced = lambda tt, t0, per, k, a, s, q1, q2: transit_model(tt, t0, per, k, a, s * (1 - k),
                                                                *q_to_u(q1, q2))
    c_free = best(free, [[T0, P, popt[2], popt[3], popt[4], *q]], hi)
    hi_s = hi[:4] + [1.0] + hi[5:]                            # s ≤ 1
    c_forced = best(forced, [[T0, P, k0, popt[3], s0, *q]     # curved valley → several starts
                             for s0 in (0.3, 0.9, 0.99) for k0 in (popt[2], 0.5 * popt[2])], hi_s)
    c_free = min(c_free, c_forced)        # the forced model is a special case of the free one
    if not np.isfinite(c_forced):
        return g, None
    return g, float(np.sqrt(max(c_forced - c_free, 0.0)))

def _target_position(lc):
    """Target RA, Dec (deg) at the middle of this sector: the catalog (TIC, epoch J2000)
    position moved by the star's proper motion (PMRA, PMDEC in mas/yr from the header).
    Proper-motion bug fix (2026-11-24): fast nearby stars (GJ 436: 1.2″/yr) move ~1 TESS pixel
    in 20 years, which made the target look offset from its own light."""
    ra, dec = float(lc.meta["RA_OBJ"]), float(lc.meta["DEC_OBJ"])
    pmra, pmdec = lc.meta.get("PMRA"), lc.meta.get("PMDEC")
    if _missing(pmra) or _missing(pmdec):
        return ra, dec
    t_mid = float(np.nanmedian(np.asarray(lc.time.value, dtype=float))) + 2457000.0   # BTJD → BJD
    years = (t_mid - 2451545.0) / 365.25                                            # since J2000
    dec_now = dec + float(pmdec) / 3.6e6 * years
    ra_now = ra + float(pmra) / 3.6e6 * years / np.cos(np.radians(dec))           # PMRA includes cos δ
    return ra_now, dec_now

def _target_pixel(lc):
    """Target's CCD (column, row) at the sector's epoch (proper motion applied), from the WCS
    of the file's aperture image. None if the file/WCS isn't available."""
    try:
        import warnings
        from astropy.io import fits
        from astropy.wcs import WCS
        with warnings.catch_warnings(), fits.open(lc.meta["FILENAME"]) as h:
            warnings.simplefilter("ignore")
            ah = h["APERTURE"].header
            x, y = WCS(ah).all_world2pix(*_target_position(lc), 0)
            return float(x) + ah["CRVAL1P"], float(y) + ah["CRVAL2P"]
    except Exception:
        return None

def centroid_check(results, n_null=200, seed=0, window=721):
    """Does the flux-weighted centroid move during transit, and where is the dimming source?
    Per sector: Δ = centroid(in-transit core) − centroid(baseline 1–3 durations away), after
    removing slow drifts (running median, transits masked). Noise σ from n_null fake transits
    at random times (captures pointing jitter / red noise). Significance: D² = Σ(Δ/σ)² over
    x, y and sectors, χ² with 2 dof per sector → Gaussian-equivalent σ.
    Source position ≈ out-of-transit centroid − Δ·(1 − δ)/δ (δ = depth); distance from the
    target's WCS position, in pixels (1 TESS pixel = 21″).
    Returns dict, or None if no usable centroid data.
    """
    from scipy.stats import chi2 as chi2_dist, norm
    popt = get_popt(results)
    t0, P = popt[0], popt[1]
    grid = np.linspace(-0.5, 0.5, 20001)                       # phase grid (orbits)
    m_grid = transit_model(t0 + grid * P, *popt)
    depth = 1 - m_grid.min()
    dur = np.mean(m_grid < 1)                                  # transit duration (orbits)
    if depth <= 0 or dur <= 0:
        return None
    core_half = 0.5 * np.mean(m_grid < 1 - 0.5 * depth)        # half-width of deep core
    rng = np.random.default_rng(seed)
    allowed = np.r_[np.linspace(4 * dur, 0.5 - 4 * dur, 500),  # fake-transit phases away from
                    np.linspace(0.5 + 4 * dur, 1 - 4 * dur, 500)]  # transit and phase 0.5
    allowed = allowed[(allowed > 0) & (allowed < 1)]
    if len(allowed) < 20:
        return None
    shifts = rng.choice(allowed, n_null)

    D2, dof, sectors = 0.0, 0, []
    for lc in results.get("raw_lcs", []):
        lc = lc.remove_nans()
        t = np.asarray(lc.time.value, float)
        cx = np.asarray(getattr(lc, "centroid_col", np.full(len(t), np.nan)).value, float)
        cy = np.asarray(getattr(lc, "centroid_row", np.full(len(t), np.nan)).value, float)
        ok = np.isfinite(t) & np.isfinite(cx) & np.isfinite(cy)
        t, cx, cy = t[ok], cx[ok], cy[ok]
        if len(t) < 500:
            continue
        phase = ((t - t0) / P) % 1                             # 0 = transit
        sym = lambda ph: np.abs((ph + 0.5) % 1 - 0.5)          # distance from phase 0
        # slow drifts: running median with transits masked, interpolated across them
        quiet = sym(phase) > dur
        trend = lambda c: np.interp(t, t[quiet], pd.Series(c[quiet]).rolling(
            window, center=True, min_periods=window // 4).median().bfill().ffill().values)
        dx, dy = cx - trend(cx), cy - trend(cy)

        def delta(shift):
            d = sym(phase - shift)
            inn, out = d < core_half, (d > dur) & (d < 3 * dur)
            if inn.sum() < 10 or out.sum() < 10:
                return None
            return dx[inn].mean() - dx[out].mean(), dy[inn].mean() - dy[out].mean(), inn, out
        real = delta(0.0)
        if real is None:
            continue
        ddx, ddy, inn, out = real
        null = np.array([v[:2] for v in (delta(sh) for sh in shifts) if v is not None])
        if len(null) < 20:
            continue
        sx, sy = null[:, 0].std(), null[:, 1].std()
        D2 += (ddx / sx) ** 2 + (ddy / sy) ** 2
        dof += 2

        scale = (1 - depth) / depth                            # centroid shift → source offset
        src = np.array([cx[out].mean() - ddx * scale, cy[out].mean() - ddy * scale])
        tgt = _target_pixel(lc)
        ref = np.array(tgt) if tgt is not None else np.array([cx[out].mean(), cy[out].mean()])
        v = src - ref
        dist = np.hypot(*v)
        dist_err = np.hypot(v[0] * sx, v[1] * sy) * scale / dist if dist > 0 else np.hypot(sx, sy) * scale
        sectors.append({"sector": lc.meta.get("SECTOR"), "dx": ddx, "dy": ddy, "sx": sx, "sy": sy,
                        "dist": dist, "dist_err": dist_err,
                        "ref": "TIC position" if tgt is not None else "out-of-transit centroid"})
    if dof == 0:
        return None
    p = chi2_dist.sf(D2, dof)
    z = float(norm.isf(p / 2)) if p > 0 else np.inf            # two-sided Gaussian equivalent
    w = np.array([1 / s["dist_err"] ** 2 for s in sectors])
    dist = float(np.sum(w * [s["dist"] for s in sectors]) / w.sum())
    dist_err = float(1 / np.sqrt(w.sum()))
    return {"sigma": z, "D2": D2, "dof": dof, "dist": dist, "dist_err": dist_err,
            "sectors": sectors}

# --- Gaia neighbour-depth check (2026-11-24, approved; design: docs/design_neighbor_depth.md) --
PSF_SIGMA_PX = 0.75          # Gaussian approximation to the TESS PSF (simulated: ±15% is harmless)
ND_RADIUS_PX = 2.5           # neighbours considered (1 TESS pixel = 21″)
ND_SYS_FRAC = 0.10           # model systematic: 10% of the predicted shift, plus a small floor
ND_SYS_FLOOR = 0.0005        # px

def _nd_terms(stars, ap, sig=PSF_SIGMA_PX):
    """stars: rows (x, y, Tmag) in aperture-image pixel coordinates; ap: boolean aperture mask.
    Returns per star (S_j, Sx_j, Sy_j): its flux inside the aperture and flux-weighted coords."""
    yy, xx = np.mgrid[0:ap.shape[0], 0:ap.shape[1]].astype(float)
    out = []
    for x, y, m in stars:
        img = 10 ** (-0.4 * m) * np.exp(-((xx - x) ** 2 + (yy - y) ** 2) / (2 * sig ** 2)) \
              / (2 * np.pi * sig ** 2) * ap
        out.append((img.sum(), (img * xx).sum(), (img * yy).sum()))
    return np.array(out)

def _nd_chi2(terms, delta, sx, sy, d_obs):
    """For each star j: can it make the observed (aperture) depth d_obs, and how well does the
    centroid shift it predicts match the measured shift delta = (Δx, Δy) ± (sx, sy)?
    Returns (chi2 per star, feasible per star). Predicted shift = moment centroid with star j
    dimmed by d_j = d_obs·S/S_j minus the undimmed centroid (aperture truncation included)."""
    S, Sx, Sy = terms.sum(0)
    chi, ok = [], []
    for Sj, Sxj, Syj in terms:
        dj = d_obs * S / Sj if Sj > 0 else np.inf
        if dj > 1:
            chi.append(np.inf); ok.append(False); continue
        pred = np.array([(Sx - dj * Sxj) / (S - dj * Sj) - Sx / S,
                         (Sy - dj * Syj) / (S - dj * Sj) - Sy / S])
        sys2 = (ND_SYS_FRAC * np.abs(pred)) ** 2 + ND_SYS_FLOOR ** 2
        chi.append(float(np.sum((np.asarray(delta) - pred) ** 2 / (np.array([sx, sy]) ** 2 + sys2))))
        ok.append(True)
    return np.array(chi), np.array(ok)

def neighbor_depth_check(results, cen):
    """Which star is eclipsing? Hypotheses: the target or each catalogue neighbour within
    ND_RADIUS_PX (TIC, Gaia-based, moved to each sector's epoch). Uses the per-sector centroid
    shifts measured by centroid_check. FAIL if the target hypothesis is rejected (χ², p < 0.27%)
    AND a neighbour fits; WEAK if the target is rejected and none fits; else PASS.
    Simulation (sims/neighbor_depth_sim.py): planets FAIL 0% (normal, crowded, PSF 15% off);
    eclipsing neighbours caught 86–94% at 1 px, 96–100% at 2 px, 10–22% at 0.5 px.
    Returns dict, or None if centroids / catalogue / WCS are unavailable."""
    if not cen or not cen.get("sectors"):
        return None
    import warnings
    from scipy.stats import chi2 as chi2_dist
    from astropy.io import fits
    from astropy.wcs import WCS
    popt = get_popt(results)
    depth = 1 - transit_model(np.array([popt[0]]), *popt)[0]          # crowding-corrected depth
    lc0 = results["raw_lcs"][0]
    try:
        from astroquery.mast import Catalogs
        q = Catalogs.query_region(f"{lc0.meta['RA_OBJ']} {lc0.meta['DEC_OBJ']}",
                                  radius=(ND_RADIUS_PX + 0.5) * 21 / 3600, catalog="TIC")
    except Exception:
        return None
    q = q[[str(d) not in ("ARTIFACT", "DUPLICATE", "SPLIT") for d in q["disposition"]]]
    q = q[np.isfinite(np.asarray(q["Tmag"], dtype=float))]
    tic = lc0.meta.get("TICID")
    is_t = np.array([int(i) == int(tic) for i in q["ID"]]) if tic else np.zeros(len(q), bool)
    if not is_t.any():
        is_t = np.asarray(q["dstArcSec"]) == np.min(q["dstArcSec"])
    order = np.r_[np.where(is_t)[0][:1], np.where(~is_t)[0]]                 # target first
    q = q[order]
    tmag_t = float(q["Tmag"][0])
    q = q[np.asarray(q["Tmag"], dtype=float) <= tmag_t + 7.5]                 # fainter can't matter
    pm = lambda c: np.nan_to_num(np.asarray(q[c], dtype=float))
    chi_tot, ok_tot, n_used = np.zeros(len(q)), np.ones(len(q), bool), 0
    for s in cen["sectors"]:
        lc = next((l for l in results["raw_lcs"] if l.meta.get("SECTOR") == s["sector"]), None)
        if lc is None:
            continue
        try:
            with warnings.catch_warnings(), fits.open(lc.meta["FILENAME"]) as h:
                warnings.simplefilter("ignore")
                ah = h["APERTURE"].header
                ap = (h["APERTURE"].data & 2) > 0
                w = WCS(ah)
        except Exception:
            continue
        years = (float(np.nanmedian(np.asarray(lc.time.value, float))) + 2457000.0 - 2451545.0) / 365.25
        dec = np.asarray(q["dec"], float) + pm("pmDEC") / 3.6e6 * years
        ra = np.asarray(q["ra"], float) + pm("pmRA") / 3.6e6 * years / np.cos(np.radians(dec))
        x, y = w.all_world2pix(ra, dec, 0)
        stars = list(zip(x, y, np.asarray(q["Tmag"], float)))
        crowd = lc.meta.get("CROWDSAP")
        d_obs = depth * (float(crowd) if not _missing(crowd) else 1.0)       # raw-aperture depth
        chi, ok = _nd_chi2(_nd_terms(stars, ap), (s["dx"], s["dy"]), s["sx"], s["sy"], d_obs)
        chi_tot += chi; ok_tot &= ok; n_used += 1
    if n_used == 0:
        return None
    crit = chi2_dist.isf(0.0027, 2 * n_used)
    fits_ok = [j for j in range(1, len(q)) if ok_tot[j] and chi_tot[j] <= crit]
    rejected = chi_tot[0] > crit
    best = min(fits_ok, key=lambda j: chi_tot[j]) if fits_ok else None
    return {"status": "FAIL" if (rejected and fits_ok) else ("WEAK" if rejected else "PASS"),
            "chi2_target": float(chi_tot[0]), "crit": float(crit), "n_neighbours": len(q) - 1,
            "n_possible": int(ok_tot[1:].sum()),
            "best_neighbour": None if best is None else
            (int(q["ID"][best]), float(q["dstArcSec"][best]), float(q["Tmag"][best]) - tmag_t)}

"""---
# 7. Vetting report
Runs every check silently and prints one report card. Planet size catches star-sized
companions (including identical-twin binaries that pass odd/even).
Verdict: any FAIL → likely false positive; all pass → planet candidate.
(Pass/fail counts, not a probability.)
"""

def vet_star(results, verbose=True):
    """Run all vetting checks on an analyze_star result and print a one-screen report."""
    lc, popt = results["lc"], get_popt(results)

    with contextlib.redirect_stdout(io.StringIO()):       # run checks without their printouts
        _, _, oe_sigma = odd_even(lc, popt)
        sec_depth, sec_err, sec_sigma, sec_ratio = secondary_eclipse(lc, popt)
        dens = density_check(results)
    g, g_sigma = grazing_check(results)
    cen = centroid_check(results) if "raw_lcs" in results else None

    # Detection strength: dip depth vs noise of the averaged in-transit points
    t = np.asarray(lc.time.value, dtype=float)
    f = np.asarray(lc.flux.value, dtype=float)
    model = transit_model(t, *popt)
    in_tr = model < 1
    depth = 1 - model.min()
    snr = depth / (np.std(f[~in_tr]) / np.sqrt(in_tr.sum()))

    # Planet size in Jupiter radii
    R = results["star_info"].get("RADIUS")
    rp_jup = popt[2] * float(R) / R_JUP if R else None

    checks = [("Detection SNR", "PASS" if snr > 7.1 else "FAIL", f"SNR = {snr:.0f}"),
              ("Odd/even depths", "N/A", "too few fully covered transits") if oe_sigma is None else
              ("Odd/even depths", "PASS" if oe_sigma < 3 else "FAIL", f"{oe_sigma:.1f}σ difference"),
              ("Secondary eclipse", "FAIL" if (sec_sigma > 3 and sec_ratio > 0.1) else "PASS",
               f"{sec_depth*1e6:.0f} ± {sec_err*1e6:.0f} ppm ({sec_ratio*100:.1f}% of transit)")]
    if dens is None:
        checks.append(("Density", "N/A", "no catalog data"))
    else:
        rho_cat, ratio, dsig, weak = dens
        if weak:
            status = "WEAK"                                # too uncertain to count
        elif (ratio < 0.5 or ratio > 2) and dsig > 3:
            status = "FAIL"
        else:
            status = "PASS"
        checks.append(("Density", status, f"transit / catalog = {ratio:.2f} ({dsig:.1f}σ)"))
    rp_capped = "Rp/Rs" in results["flags"] and popt[2] > 0.5   # stuck at the 1.0 cap
    if rp_jup is None:
        checks.append(("Planet size", "N/A", "no stellar radius"))
    elif rp_capped:          # true Rp/Rs may be larger (e.g. white-dwarf host) → lower limit
        checks.append(("Planet size", "FAIL" if rp_jup >= 2.5 else "WEAK",
                       f"Rp ≥ {rp_jup:.2f} R_Jup (Rp/Rs at its cap → lower limit)"))
    else:
        checks.append(("Planet size", "PASS" if rp_jup < 2.5 else "FAIL",
                       f"Rp = {rp_jup:.2f} R_Jup"))
    if g_sigma is None:
        checks.append(("Grazing", "N/A", f"b + Rp/Rs = {g + 1:.2f} (forced fit failed)"))
    else:
        checks.append(("Grazing", "WARN" if g_sigma > 3 else "PASS",
                       f"b + Rp/Rs = {g + 1:.2f}; grazing at {g_sigma:.1f}σ (profile)"))

    if cen is None:
        checks.append(("Centroid", "N/A", "no usable centroid data"))
    else:
        detail = (f"shift {cen['sigma']:.1f}σ, source {cen['dist']:.2f} ± "
                  f"{cen['dist_err']:.2f} px from target")
        if cen["sigma"] > 3 and cen["dist"] > 1:
            status = "FAIL"                                # signal from a neighbouring star
        elif cen["dist_err"] > 1:
            status = "WEAK"                                # too noisy to locate the source
        else:
            status = "PASS"
        checks.append(("Centroid", status, detail))

    nd = neighbor_depth_check(results, cen)
    if nd is None:
        checks.append(("Neighbor depth", "N/A", "no centroids / catalogue / WCS"))
    else:
        detail = (f"target χ² {nd['chi2_target']:.1f} (limit {nd['crit']:.1f}); "
                  f"{nd['n_possible']}/{nd['n_neighbours']} neighbours bright enough")
        if nd["best_neighbour"]:
            tid, sep, dmag = nd["best_neighbour"]
            detail += f"; fits TIC {tid} ({sep:.0f}″, Δmag {dmag:.1f})"
        checks.append(("Neighbor depth", nd["status"], detail))

    statuses = [c[1] for c in checks]
    n_run = sum(s in ("PASS", "FAIL", "WARN") for s in statuses)  # WEAK / N/A don't count
    n_pass = statuses.count("PASS")
    if "FAIL" in statuses:
        verdict = "LIKELY FALSE POSITIVE"
    elif "WARN" in statuses:
        verdict = "CANDIDATE WITH WARNINGS"
    elif n_pass < len(checks):
        verdict = "PLANET CANDIDATE (some checks weak or not run)"
    else:
        verdict = "PLANET CANDIDATE"

    if verbose:
        print(f"\n===== {results['star']}: VETTING REPORT =====")
        print(f"Period = {popt[1]:.5f} d | Rp/R★ = {popt[2]:.4f} | depth = {depth*100:.2f}%")
        for name, status, detail in checks:
            print(f"  {name:18s} {status:5s} {detail}")
        if results["flags"]:
            print(f"  Fit note: {results['flags']} at a boundary", end="")
            if results.get("b_upper") is not None:
                print(f" → b < {results['b_upper']:.2f}, inc > {results['inc_lower']:.1f}°", end="")
            elif "b_upper" in results:
                print(" → b unconstrained", end="")
            print()
        print(f"VERDICT: {verdict} ({n_pass}/{n_run} checks passed)")

    report = {"checks": checks, "snr": snr, "rp_jup": rp_jup, "verdict": verdict,
              "centroid": cen, "neighbor_depth": nd,
              "n_pass": n_pass, "n_run": n_run}
    results["vetting"] = report
    return report

"""---
# 8. Full pipeline
download → search one sector → fit one sector → (more sectors) clean all with refined
timing and refit → automatic upper limit if b is flagged → optional vetting report.
"""

def analyze_star(star_name, n_sectors=1, plot=False, verbose=True, vet=False,
                 period_hint=None):
    """Run the full pipeline on a star. Returns a dictionary of results.
    period_hint: a known period (e.g. the TOI's); the search then only looks within ±2% of
    it (always the 1× window when it fits), so we vet that signal and not a different one.
    """
    lcs = download(star_name, n_sectors)
    star_info, star_source = get_star_info(lcs[0])
    ld_prior, ld_source = ld_prior_for(star_info)

    # Search and first fit on ONE sector
    period_choice = None
    if period_hint is None:
        period, t0, duration, depth = search(clean(lcs[0]), plot=plot)
    else:
        period, t0, duration, depth, period_choice = search_near(clean(lcs[0]), period_hint)
    c1 = clean(lcs[0], period=period, t0=t0, duration=duration)
    popt, errs, inc, inc_err, flags, pcov = fit_transit(c1, period, t0, duration, depth,
                                                        plot=plot and len(lcs) == 1,
                                                        return_pcov=True, ld_prior=ld_prior)
    cleaned = c1

    # Refine with all sectors, timing window set by the 1-sector uncertainties
    ephem_notes = []
    if len(lcs) > 1:                       # timing fix: per-sector transit times → straight line
        T0e, Pe, sT0, sP, ephem_notes = per_sector_ephemeris(lcs, popt, errs, duration, depth,
                                                             ld_prior)
        cleaned = clean_all(lcs, period=Pe, t0=T0e, duration=duration)
        popt, errs, inc, inc_err, flags, pcov = fit_transit(cleaned, period, t0, duration, depth,
                                                            start=np.r_[T0e, Pe, popt[2:]],
                                                            start_errs=[sT0, sP],
                                                            plot=plot, return_pcov=True,
                                                            ld_prior=ld_prior)

    rho = 3 * np.pi / (G * (popt[1] * 86400)**2) * popt[3]**3 / 1000
    results = {"star": star_name, "n_sectors": len(lcs), "flags": flags,
               "inc": (inc, inc_err), "density": (rho, rho * 3 * errs[3] / popt[3]),
               "lc": cleaned, "star_info": star_info, "period_choice": period_choice,
               "ld_source": ld_source, "ld_prior": ld_prior, "raw_lcs": lcs,
               "ephem_notes": "; ".join(ephem_notes),
               "star_source": ", ".join(f"{k}={v}" for k, v in star_source.items())}
    for name, val, err in zip(PARAM_NAMES, popt, errs):
        results[name] = (val, err)
    results["cov_rp_b"] = pcov[2, 4]                  # for the grazing check

    # Automatic upper limit when b is stuck near 0 (nearly edge-on)
    if "b" in flags and popt[4] < 0.5:
        results["b_upper"], results["inc_lower"] = profile_b(cleaned, popt, plot=plot,
                                                             ld_prior=ld_prior)

    if verbose:
        print(f"\n{'━' * 50}\n=== {star_name} ({len(lcs)} sector(s)) ===")
        for name in PARAM_NAMES:
            v, e = results[name]
            print(f"{name:7s} = {v:.5f} ± {e:.5f}")
        print(f"inc     = {inc:.2f} ± {inc_err:.2f} deg")
        print(f"density = {rho:.2f} ± {results['density'][1]:.2f} g/cm³")
        if flags:
            print("⚠️ Flags:", flags)
        if "b_upper" in results:
            if results["b_upper"] is None:
                print("→ b unconstrained (data can't limit it)")
            else:
                print(f"→ b < {results['b_upper']:.2f} (95%), so inc > {results['inc_lower']:.1f}°")

    if vet:
        vet_star(results, verbose=verbose)
    return results

