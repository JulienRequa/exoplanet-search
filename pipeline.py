"""---
# 10. Batch run
Run the pipeline on a list of known planets and collect one summary row per star.
Published periods (approximate) are a quick sanity check: does the search recover the
right period, or a harmonic (½× or 2×)?
"""

# Known transiting planets: star name → approximate published period (days)
TARGETS = {
    "WASP-18": 0.9415, "WASP-121": 1.2749, "WASP-19": 0.7888, "WASP-43": 0.8135,
    "HD 189733": 2.2186, "HD 209458": 3.5247, "KELT-9": 1.4811, "WASP-33": 1.2199,
    "HAT-P-7": 2.2047, "WASP-62": 4.4119, "WASP-100": 2.8494, "WASP-126": 3.2889,
    "pi Men": 6.2680,
}

def period_match(P, P_pub, tol=0.01):
    """Did we find the published period, or a harmonic of it?"""
    for factor, label in [(1, "yes"), (2, "2×"), (0.5, "½×")]:
        if abs(P - factor * P_pub) / (factor * P_pub) < tol:
            return label
    return "NO"

def batch_run(targets, n_sectors=2, use_hint=False):
    """Run analyze_star on every target (star → published/TOI period).
    use_hint=True passes each target's period as period_hint.
    Returns (summary table, full results by star).
    """
    rows, all_results = [], {}
    for star, P_pub in targets.items():
        start = time.time()
        try:
            with contextlib.redirect_stdout(io.StringIO()):          # silence each star's printout
                r = analyze_star(star, n_sectors=n_sectors, verbose=False, vet=True,
                                 period_hint=P_pub if use_hint else None)
            all_results[star] = r
            v = r["vetting"]
            rows.append({"star": star, "sectors": r["n_sectors"],
                         "period": round(r["period"][0], 5), "published P": P_pub,
                         "P match": period_match(r["period"][0], P_pub),
                         "period choice": r["period_choice"],
                         "star source": r["star_source"],
                         "Rp/Rs": round(r["Rp/Rs"][0], 4),
                         "Rp (R_Jup)": round(v["rp_jup"], 2) if v["rp_jup"] else None,
                         "SNR": round(v["snr"]), "checks": f"{v['n_pass']}/{v['n_run']}",
                         "verdict": v["verdict"], "flags": ", ".join(r["flags"]),
                         "time (s)": round(time.time() - start)})
            print(f"✓ {star} ({rows[-1]['time (s)']} s)")
        except Exception as e:                                       # one bad star shouldn't stop the run
            rows.append({"star": star, "verdict": f"ERROR: {type(e).__name__}"})
            print(f"✗ {star}: {type(e).__name__}: {str(e)[:80]}")
    return pd.DataFrame(rows), all_results


