def period_match(P, P_pub, tol=0.01):
    """Did we find the published period, or a harmonic of it?"""
    for factor, label in [(1, "yes"), (2, "2×"), (0.5, "½×")]:
        if abs(P - factor * P_pub) / (factor * P_pub) < tol:
            return label
    return "NO"

def batch_run(targets, n_sectors=2):
    """Run analyze_star on every target. Returns (summary table, full results by star)."""
    rows, all_results = [], {}
    for star, P_pub in targets.items():
        start = time.time()
        try:
            with contextlib.redirect_stdout(io.StringIO()):          # silence each star's printout
                r = analyze_star(star, n_sectors=n_sectors, verbose=False, vet=True)
            all_results[star] = r
            v = r["vetting"]
            rows.append({"star": star, "sectors": r["n_sectors"],
                         "period": round(r["period"][0], 5), "published P": P_pub,
                         "P match": period_match(r["period"][0], P_pub),
                         "Rp/Rs": round(r["Rp/Rs"][0], 4),
                         "Rp (R_Jup)": round(v["rp_jup"], 2) if v["rp_jup"] else None,
                         "SNR": round(v["snr"]), "checks": f"{v['n_pass']}/{v['n_run']}",
                         "verdict": v["verdict"], "flags": ", ".join(r["flags"]),
                         "time (s)": round(time.time() - start)})
            print(f"✓ {star} ({rows[-1]['time (s)']} s)")
        except Exception as e:                                       # one bad star shouldn't stop the run
            rows.append({"star": star, "verdict": f"ERROR: {type(e).__name__}"})
            print(f"✗ {star}: {type(e).__name__}: {str(e)[:80]}")
    return pd.DataFrame(rows), all_results

summary, all_results = batch_run(TARGETS)
